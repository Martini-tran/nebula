async (page) => {
  const checks=[];
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
  try {
  await page.goto('http://127.0.0.1:5185/ai-flow/list');
  await page.setViewportSize({width:1440,height:1000});
  if(await page.getByRole('switch',{name:'深色二级菜单'}).getAttribute('aria-checked')!=='true') await page.getByRole('switch',{name:'深色二级菜单'}).click();
  check(await page.locator('.secondary-nav').evaluate(e=>e.classList.contains('secondary-dark')),'dark menu');
  await page.waitForFunction(()=>Object.entries(localStorage).some(([key,value])=>key.includes('dual-sidebar-v1') && value.includes('"semiDarkSidebarSub":true')));
  await page.waitForFunction(()=>document.getAnimations().every(a=>a.playState!=='running'));
  await page.screenshot({path:'output/playwright/layout-implemented-dark.png'});
  await page.reload();
  await page.locator('.dual-layout').waitFor();
  check(await page.getByRole('switch',{name:'深色二级菜单'}).getAttribute('aria-checked')==='true','theme persistence');
  await page.getByRole('switch',{name:'深色二级菜单'}).click();
  await page.getByRole('button',{name:'收起二级菜单',exact:true}).click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('main').getBoundingClientRect().left-76)<1);
  check(await page.locator('.secondary-nav').getAttribute('inert')!==null,'collapsed menu removed from keyboard navigation');
  await page.getByRole('button',{name:'展开二级菜单',exact:true}).click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('main').getBoundingClientRect().left-298)<1);
  await page.waitForFunction(()=>Math.abs(parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--nebula-content-width'))-document.querySelector('main').clientWidth)<2);
  checks.push('content size observer');
  await page.getByRole('menuitem',{name:'知识库',exact:true}).click();
  await page.waitForFunction(()=>location.pathname==='/ai-knowledge/list');
  await page.getByRole('button',{name:'内容管理',exact:true}).click();
  await page.waitForFunction(()=>location.pathname==='/blog/tag' && location.search==='?scope=team');
  checks.push('module navigation preserves query');
  await page.getByRole('button',{name:'AI 工作室',exact:true}).click();
  await page.waitForFunction(()=>location.pathname==='/ai-knowledge/list');
  checks.push('last visited child restored');
  await page.locator('.dual-tabs .tab-item').filter({hasText:'流程列表'}).click();
  await page.waitForFunction(()=>location.pathname==='/ai-flow/list');
  checks.push('existing tabs navigate correctly');
  await page.context().route('https://example.test/docs',route=>route.fulfill({contentType:'text/html',body:'<title>Layout external link fixture</title>'}));
  const popupPromise=page.waitForEvent('popup');
  await page.getByRole('button',{name:'使用文档',exact:true}).click();
  const popup=await popupPromise;
  await popup.waitForURL('https://example.test/docs');
  checks.push('external link popup');
  await popup.close();
  await page.evaluate(async()=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/ai-flow/editor?flowCode=weekly-report');});
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.domain-rail')).display==='none');
  await page.waitForFunction(()=>Math.round(document.querySelector('main').getBoundingClientRect().left)===0);
  check(await page.locator('.dual-tabs').count()===0,'editor keeps full content layout');
  await page.screenshot({path:'output/playwright/layout-editor-fullscreen.png'});
  await page.evaluate(async()=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/ai-flow/list');});
  await page.waitForFunction(()=>Math.round(document.querySelector('main').getBoundingClientRect().left)===298);
  checks.push('editor exit restores dual layout');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('.dual-layout').classList.contains('is-mobile'));
  await page.waitForFunction(()=>Math.round(document.querySelector('main').getBoundingClientRect().left)===64);
  check(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'mobile shell has no page overflow');
  await page.getByRole('button',{name:'展开二级菜单',exact:true}).click();
  await page.locator('.navigation-scrim').waitFor();
  await page.screenshot({path:'output/playwright/layout-implemented-mobile.png'});
  await page.getByRole('menuitem',{name:'知识库',exact:true}).click();
  await page.waitForFunction(()=>location.pathname==='/ai-knowledge/list');
  await page.locator('.navigation-scrim').waitFor({state:'hidden'});
  checks.push('mobile selection closes drawer');
  await page.getByRole('button',{name:'展开二级菜单',exact:true}).click();
  await page.keyboard.press('Escape');
  await page.locator('.navigation-scrim').waitFor({state:'hidden'});
  checks.push('escape closes mobile drawer');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.dual-tabs .tab-item').filter({hasText:'流程列表'}).click();
  await page.waitForFunction(()=>location.pathname==='/ai-flow/list');
  await page.screenshot({path:'output/playwright/layout-implemented-desktop.png'});
  return checks;
  } catch(error) { throw new Error(JSON.stringify({checks,url:page.url(),error:error.message})); }
}
